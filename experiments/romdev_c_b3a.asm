Frame:
        lda #2
        sta VBLANK
        sta VSYNC
        sta WSYNC
        sta WSYNC
        sta WSYNC
        lda #0
        sta VSYNC

        lda SWCHB
        sta SwitchState
        jsr UpdateMode
        sta WSYNC           ; VBLANK scanline 1
        jsr SelectPtrs
        sta WSYNC           ; VBLANK scanline 2
        ldx Mode
        lda XTable,x
        sta PlayerX
        jsr PositionP0      ; owns WSYNC: VBLANK scanline 3
        sta WSYNC           ; VBLANK scanline 4
        sta HMOVE           ; within HBLANK
        ldx #33
VBlankPad:
        sta WSYNC           ; lines 5..37
        dex
        bne VBlankPad

        lda #0
        sta VBLANK
        ldy #192
Visible:
        sta WSYNC           ; begin next of 192 visible scanlines
        dey                 ; 191 .. 0, source tables in reverse row order
        lda #0
        sta PF0             ; left 4 PF cells unused at all three centers
        lda (L1Ptr),y
        sta PF1
        lda (L2Ptr),y
        sta PF2
        lda Troll2,y
        sta GRP0            ; P0 updated with live PF writes on same scanline
        lda (R0Ptr),y
        sta PF0             ; pre-right-half PF0 write
        lda (R1Ptr),y
        sta PF1
        lda #0
        sta PF2             ; rightmost PF2 unused at all three centers
        tya
        bne Visible

        sta WSYNC           ; overscan line 1: sync before cleanup, avoid 263-line frame
        lda #2
        sta VBLANK
        lda #0
        sta PF0
        sta PF1
        sta PF2
        sta GRP0
        ldx #29
Overscan:
        sta WSYNC
        dex
        bne Overscan
        jmp Frame           ; 3+37+192+30 NTSC if kernels stay under 76 cycles

UpdateMode:
        lda SwitchState
        and #2
        bne SelectReleased
        lda PrevSelect
        bne SelectDone
        lda #1
        sta PrevSelect
        inc Mode
        lda Mode
        cmp #3
        bne SelectDone
        lda #0
        sta Mode
SelectDone:
        rts
SelectReleased:
        lda #0
        sta PrevSelect
        rts

; Select exactly four full-range 192-row PF tables, no framebuffer.
; The same ZeroTable is used for absent parts, ROM remains <4K.
SelectPtrs:
        lda Mode
        beq Set56
        cmp #1
        beq Set80
        jmp Set104
Set56:
        lda #<L1_56
        sta L1Ptr
        lda #>L1_56
        sta L1Ptr+1
        lda #<L2_56
        sta L2Ptr
        lda #>L2_56
        sta L2Ptr+1
        lda #<ZeroTable
        sta R0Ptr
        sta R1Ptr
        lda #>ZeroTable
        sta R0Ptr+1
        sta R1Ptr+1
        rts
Set80:
        lda #<ZeroTable
        sta L1Ptr
        lda #>ZeroTable
        sta L1Ptr+1
        lda #<L2_80
        sta L2Ptr
        lda #>L2_80
        sta L2Ptr+1
        lda #<R0_80
        sta R0Ptr
        lda #>R0_80
        sta R0Ptr+1
        lda #<R1_80
        sta R1Ptr
        lda #>R1_80
        sta R1Ptr+1
        rts
Set104:
        lda #<ZeroTable
        sta L1Ptr
        sta L2Ptr
        lda #>ZeroTable
        sta L1Ptr+1
        sta L2Ptr+1
        lda #<R0_104
        sta R0Ptr
        lda #>R0_104
        sta R0Ptr+1
        lda #<R1_104
        sta R1Ptr
        lda #>R1_104
        sta R1Ptr+1
        rts

