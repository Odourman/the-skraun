; ROMDEV C: P02-B3a ONLY - asymmetric PF diagnostic (3 SELECT centers)
; Atari 2600 NTSC, 4K, original 6507/TIA; no joystick-following halo or game logic.
; Centers: x=56,80,104 logical TIA color clocks; fixed Y=96; level-2 gray P0.
; Hollow ellipse band: 0.82 <= normalized radial score <= 1.12.
; CTRLPF=0: left and right halves rewritten on EVERY scanline.
; Unused left PF0 and right PF2 are explicitly cleared; four pointer tables per mode.
; Indexed table data stored bottom-first because Y descends 191 -> 0 from top to bottom.
; All rows of the C sprite are upright (actual reference gray A from historical prototype).
        processor 6502
VSYNC       = $00
VBLANK      = $01
WSYNC       = $02
NUSIZ0      = $04
COLUP0      = $06
COLUPF      = $08
COLUBK      = $09
